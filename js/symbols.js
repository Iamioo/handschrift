const P = 0.55;
const L = (...pts) => pts.map(([x, y]) => [x, y, P]);
const dot = (x, y) => [[x, y, 0.75], [x + 0.01, y + 0.008, 0.75]];

function ring(cx, cy, r, steps = 14) {
  const out = [];
  for (let i = 0; i <= steps + 1; i++) {
    const t = (i / steps) * Math.PI * 2 - 0.4;
    out.push([cx + Math.cos(t) * r, cy + Math.sin(t) * r, P]);
  }
  return out;
}

function wave(x1, x2, y, amp) {
  const out = [];
  for (let i = 0; i <= 10; i++) {
    const t = i / 10;
    out.push([x1 + (x2 - x1) * t, y + Math.sin(t * Math.PI * 2) * amp, P]);
  }
  return out;
}

